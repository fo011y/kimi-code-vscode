"""
Заменяет русские строковые литералы на ключи i18n (S.xxx / fmt(S.xxx) / L.xxx).
Идемпотентен: если new уже есть, а old нет — пропускает пару.
Несовпадения собирает и печатает, не падая.
"""
import io, os, sys

os.chdir(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))

errors = []

def apply(path, pairs):
    with io.open(path, encoding='utf-8') as f:
        text = f.read()
    for old, new, cnt in pairs:
        if old not in text:
            if new in text:
                continue  # уже применено
            errors.append((path, cnt, 0, old[:90]))
            continue
        c = text.count(old)
        if c != cnt:
            errors.append((path, cnt, c, old[:90]))
            continue
        text = text.replace(old, new)
    with io.open(path, 'w', encoding='utf-8', newline='') as f:
        f.write(text)

